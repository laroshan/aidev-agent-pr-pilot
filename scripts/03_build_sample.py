"""Audit the human baseline and build the matched sample of agent/human PR pairs.

Matching uses only repository, task type, creation time and author fields, never
an outcome (state, merge or close times). The one exception is the table-level
snapshot date, which is inferred from the latest timestamp in the human table.

Writes:
    results/human_baseline_audit.md
    results/matched_pairs.csv
    results/sample.md

Usage:
    python scripts/03_build_sample.py
"""
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aidev  # noqa: E402


def fmt(n):
    return format(int(n), ",")


def audit(agent, human, flags, window_end):
    t_h = aidev.snapshot_lower_bound(human)
    t_a = aidev.snapshot_lower_bound(agent)
    dropped = flags.any(axis=1)
    lines = [
        "# Human-baseline audit", "",
        "Generated by `scripts/03_build_sample.py`.", "",
        "## Snapshot dates (latest timestamp of any kind in each table)", "",
        "| Table | Latest timestamp | PRs |", "| --- | --- | ---: |",
        "| `human_pull_request` | %s | %s |" % (t_h, fmt(len(human))),
        "| `pull_request` (agent) | %s | %s |" % (t_a, fmt(len(agent))),
        "",
        "Gap between the two: %.1f days. Study window: PRs created on or before %s, "
        "so every PR has %d observed days in its own table." % (
            (t_a - t_h).total_seconds() / 86400, window_end, aidev.HORIZON_DAYS),
        "",
        "## PRs in the human table that the cleaning rules drop", "",
        "| Rule | PRs | Share of human table |", "| --- | ---: | ---: |",
    ]
    for rule in flags.columns:
        k = int(flags[rule].sum())
        lines.append("| %s | %s | %.1f%% |" % (rule.replace("_", " "), fmt(k), 100 * k / len(human)))
    lines.append("| **any rule** | **%s** | **%.1f%%** |" % (
        fmt(dropped.sum()), 100 * dropped.sum() / len(human)))
    repos = pd.read_parquet(aidev.path("repository"), columns=["url", "stars"])
    h_repos = repos[repos["url"].isin(set(human["repo_url"]))]
    lines += ["", "Repositories with human PRs: %s; %s of them are in `repository` (the rest have "
              "no AIDev-pop agent PRs), with %s to %s stars." % (
                  fmt(human["repo_url"].nunique()), fmt(len(h_repos)),
                  fmt(h_repos["stars"].min()), fmt(h_repos["stars"].max()))]
    lines += ["", "Most frequent logins dropped by the account rule:", "",
              "| Login | PRs |", "| --- | ---: |"]
    top = human.loc[flags["bot_or_automation_account"], "user"].value_counts().head(12)
    lines += ["| `%s` | %s |" % (u, fmt(n)) for u, n in top.items()]
    lines.append("")
    return lines


def build_pairs(agent_pool, human_pool, rng):
    cand = agent_pool[["id", "repo_url", "type", "created_at"]].merge(
        human_pool[["id", "repo_url", "type", "created_at"]],
        on=["repo_url", "type"], suffixes=("_a", "_h"))
    cand["days_apart"] = (cand["created_at_a"] - cand["created_at_h"]).abs().dt.total_seconds() / 86400
    cand = cand[cand["days_apart"] <= aidev.WINDOW_DAYS]
    cand = cand.sort_values(["id_a", "days_apart", "id_h"])
    by_agent = {k: g for k, g in cand.groupby("id_a", sort=True)}

    order = rng.permutation(np.array(sorted(by_agent)))
    used_h, per_repo, pairs = set(), {}, []
    for a_id in order:
        g = by_agent[a_id]
        repo = g["repo_url"].iat[0]
        if per_repo.get(repo, 0) >= aidev.CAP_PER_REPO:
            continue
        free = g[~g["id_h"].isin(used_h)]
        if free.empty:
            continue
        best = free.iloc[0]                      # closest in time, then lowest human id
        used_h.add(best["id_h"])
        per_repo[repo] = per_repo.get(repo, 0) + 1
        pairs.append({"agent_pr_id": int(a_id), "human_pr_id": int(best["id_h"]),
                      "repo_url": repo, "type": best["type"],
                      "days_apart": round(float(best["days_apart"]), 3)})
        if len(pairs) == aidev.N_PAIRS:
            break
    return pd.DataFrame(pairs), len(by_agent)


def agent_size(pr_ids):
    """Lines changed and files touched per agent PR, merge commits excluded."""
    det = aidev.read_for_prs("pr_commit_details", pr_ids,
                             ["sha", "pr_id", "message", "commit_stats_additions",
                              "commit_stats_deletions", "filename"])
    det = det[~det["message"].fillna("").str.match(r"Merge\b")]
    commits = det.drop_duplicates(["pr_id", "sha"])
    lines = (commits["commit_stats_additions"] + commits["commit_stats_deletions"]).groupby(
        commits["pr_id"]).sum()
    files = det.dropna(subset=["filename"]).groupby("pr_id")["filename"].nunique()
    return pd.DataFrame({"lines_changed": lines, "files_changed": files})


def main():
    agent = aidev.load_agent_prs()
    human = aidev.load_human_prs()
    flags = aidev.human_exclusions(human, set(agent["html_url"]))
    window_end = aidev.study_window_end(human)

    lines = audit(agent, human, flags, window_end)
    with open(os.path.join(aidev.RESULTS_DIR, "human_baseline_audit.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))

    human_pool = human[~flags.any(axis=1) & (human["created_at"] <= window_end)]
    agent_pool = agent[(agent["created_at"] <= window_end)
                       & agent["repo_url"].isin(set(human_pool["repo_url"]))]
    pairs, n_matchable = build_pairs(agent_pool, human_pool, np.random.default_rng(aidev.SEED))

    a = agent.set_index("id")
    h = human.set_index("id")
    pairs.insert(0, "pair", range(1, len(pairs) + 1))
    pairs["agent"] = pairs["agent_pr_id"].map(a["agent"])
    pairs["agent_url"] = pairs["agent_pr_id"].map(a["html_url"])
    pairs["human_url"] = pairs["human_pr_id"].map(h["html_url"])
    pairs["agent_created_at"] = pairs["agent_pr_id"].map(a["created_at"])
    pairs["human_created_at"] = pairs["human_pr_id"].map(h["created_at"])
    pairs.to_csv(os.path.join(aidev.RESULTS_DIR, "matched_pairs.csv"), index=False)

    size = agent_size(pairs["agent_pr_id"])
    size = size.reindex(pairs["agent_pr_id"])
    per_repo = pairs.groupby("repo_url").size()
    out = [
        "# Matched sample", "",
        "Generated by `scripts/03_build_sample.py`.", "",
        "| | |", "| --- | ---: |",
        "| Cleaned human PRs in the study window | %s |" % fmt(len(human_pool)),
        "| Agent PRs in the same repos and window | %s |" % fmt(len(agent_pool)),
        "| Agent PRs with at least one candidate match | %s |" % fmt(n_matchable),
        "| Matched pairs | %s |" % fmt(len(pairs)),
        "| Repositories | %s |" % fmt(per_repo.size),
        "| Pairs per repository (max) | %d |" % per_repo.max(),
        "| Days between the two PRs' creation, median (max) | %.1f (%.1f) |" % (
            pairs["days_apart"].median(), pairs["days_apart"].max()),
        "| Agent PRs created, earliest to latest | %s to %s |" % (
            pairs["agent_created_at"].min().date(), pairs["agent_created_at"].max().date()),
        "",
        "## Pairs by agent", "", "| Agent | Pairs |", "| --- | ---: |",
    ]
    out += ["| %s | %d |" % (k, v) for k, v in pairs["agent"].value_counts().items()]
    out += ["", "## Pairs by task type (LLM label shipped with AIDev)", "",
            "| Type | Pairs |", "| --- | ---: |"]
    out += ["| %s | %d |" % (k, v) for k, v in pairs["type"].value_counts().items()]
    out += ["", "## Size of the sampled agent PRs (human PRs have no size data)", "",
            "Merge commits excluded. %d of %d agent PRs have commit details." % (
                size["lines_changed"].notna().sum(), len(size)), "",
            "| Measure | Median | IQR |", "| --- | ---: | --- |"]
    for col in ("lines_changed", "files_changed"):
        q = size[col].quantile([0.25, 0.5, 0.75])
        out.append("| %s | %.0f | %.0f to %.0f |" % (col.replace("_", " "), q[0.5], q[0.25], q[0.75]))
    out.append("")
    with open(os.path.join(aidev.RESULTS_DIR, "sample.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
