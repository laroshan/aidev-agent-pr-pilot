"""Record which AIDev v3 tables and fields exist, and which PRs they cover.

Writes results/schema.md. Reads only the files fetched by 01_download_data.py.

Usage:
    python scripts/02_inspect_schema.py [--data-dir data/aidev_v3]
"""
import argparse
import os

import pandas as pd
import pyarrow.parquet as pq

TABLES = [
    "pull_request", "human_pull_request", "repository", "pr_task_type",
    "human_pr_task_type", "pr_reviews", "pr_comments", "pr_review_comments_v2",
    "pr_commits", "pr_commit_details", "pr_timeline",
]
# Sub-resource tables and the column that links them to a PR.
PR_KEY = {
    "pr_reviews": "pr_id", "pr_comments": "pr_id", "pr_commits": "pr_id",
    "pr_commit_details": "pr_id", "pr_timeline": "pr_id",
}
CI_WORDS = ("check", "status", "ci", "workflow", "action", "build")


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data-dir", default=os.path.join(here, "..", "data", "aidev_v3"))
    ap.add_argument("--out", default=os.path.join(here, "..", "results", "schema.md"))
    args = ap.parse_args()
    path = lambda t: os.path.join(args.data_dir, t + ".parquet")

    lines = ["# AIDev v3 schema as downloaded", "",
             "Generated by `scripts/02_inspect_schema.py`.", ""]

    # 1. Tables, row counts, columns and types.
    lines += ["## Tables and columns", "", "| Table | Rows | Columns (type) |", "| --- | ---: | --- |"]
    for t in TABLES:
        f = pq.ParquetFile(path(t))
        cols = ", ".join("`%s` (%s)" % (c.name, c.physical_type.lower()) for c in f.schema)
        lines.append("| `%s` | %s | %s |" % (t, format(f.metadata.num_rows, ","), cols))
    lines.append("")

    # 2. Which PRs each sub-resource table covers.
    agent = pd.read_parquet(path("pull_request"), columns=["id", "agent", "created_at", "html_url"])
    human = pd.read_parquet(path("human_pull_request"), columns=["id", "created_at", "html_url"])
    agent_ids, human_ids = set(agent["id"]), set(human["id"])
    lines += ["## PR coverage of the sub-resource tables", "",
              "Agent PRs: %s (`pull_request`). Human PRs: %s (`human_pull_request`). "
              "The two tables share no `id` values, but %d PRs appear in both by `html_url`." % (
                  format(len(agent_ids), ","), format(len(human_ids), ","),
                  len(set(agent["html_url"]) & set(human["html_url"]))), "",
              "| Table | Agent PRs with >=1 row | Human PRs with >=1 row | Max rows for one PR "
              "| PRs with exactly 30 rows |",
              "| --- | ---: | ---: | ---: | ---: |"]
    for t, key in PR_KEY.items():
        ids = pd.read_parquet(path(t), columns=[key])[key]
        per_pr = ids.value_counts()
        present = set(per_pr.index)
        lines.append("| `%s` | %s | %s | %d | %s |" % (
            t, format(len(present & agent_ids), ","), format(len(present & human_ids), ","),
            per_pr.max(), format(int((per_pr == 30).sum()), ",")))
    # Inline review comments link to a review, not directly to a PR.
    rc = pd.read_parquet(path("pr_review_comments_v2"), columns=["pull_request_review_id"])
    rv = pd.read_parquet(path("pr_reviews"), columns=["id", "pr_id"])
    rc_pr = rc.merge(rv, left_on="pull_request_review_id", right_on="id", how="left")["pr_id"]
    present = set(rc_pr.dropna().astype("int64"))
    lines.append("| `pr_review_comments_v2` (via `pr_reviews`) | %s | %s | %d | %s |" % (
        format(len(present & agent_ids), ","), format(len(present & human_ids), ","),
        rc_pr.value_counts().max(), format(int((rc_pr.value_counts() == 30).sum()), ",")))
    lines.append("")
    lines.append("Inline review comments that do not join to any review: %s of %s." % (
        format(int(rc_pr.isna().sum()), ","), format(len(rc_pr), ",")))
    lines.append("")

    # 3. Date ranges.
    lines += ["## Creation dates", "", "| Set | Earliest | Latest |", "| --- | --- | --- |"]
    for name, df in (("agent PRs", agent), ("human PRs", human)):
        ts = pd.to_datetime(df["created_at"], utc=True)
        lines.append("| %s | %s | %s |" % (name, ts.min().date(), ts.max().date()))
    lines.append("")

    # 4. Timeline event types, and whether anything looks like CI.
    tl = pd.read_parquet(path("pr_timeline"), columns=["pr_id", "event", "commit_id", "message"])
    counts = tl["event"].value_counts()
    lines += ["## `pr_timeline` event types", "", "| Event | Rows |", "| --- | ---: |"]
    lines += ["| `%s` | %s |" % (e, format(n, ",")) for e, n in counts.items()]
    ref = tl[tl["event"] == "referenced"]
    lines += ["", "`cross-referenced` events: %d. `referenced` events: %s, of which %s have a "
              "commit SHA and %s have a message." % (
                  int((tl["event"] == "cross-referenced").sum()), format(len(ref), ","),
                  format(int(ref["commit_id"].notna().sum()), ","),
                  format(int(ref["message"].notna().sum()), ",")), ""]
    ci_cols = ["%s.%s" % (t, c) for t in TABLES for c in pq.ParquetFile(path(t)).schema.names
               if any(w in c.lower() for w in CI_WORDS)]
    ci_events = [e for e in counts.index if any(w in str(e).lower() for w in CI_WORDS)]
    lines += ["## CI / check results", "",
              "Columns whose name mentions check/status/ci/workflow/action/build: %s." % (
                  ", ".join("`%s`" % c for c in ci_cols) or "none"),
              "Timeline events whose name mentions those words: %s." % (
                  ", ".join("`%s`" % e for e in ci_events) or "none"), ""]

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
